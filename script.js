const outputBox = document.getElementById('output-box');
const quoteBtn = document.getElementById('quote-btn');
const cardBtn = document.getElementById('card-btn');
let lastQuoteIndex = -1;
let lastCardIndex = -1;
// Функция для перезапуска анимации появления текста
function triggerAnimation(element) {
element.style.animation = 'none';
element.offsetHeight; // принудительный reflow
element.style.animation = null;
}
// Показ случайной цитаты
quoteBtn.addEventListener('click', () => {
let randomIndex;
do {
randomIndex = Math.floor(Math.random() * quotes.length);
} while (randomIndex === lastQuoteIndex && quotes.length > 1);
lastQuoteIndex = randomIndex;
mainTitle.style.fontSize = '1.5rem';
mainTitle.style.opacity = '0.7';
outputBox.classList.remove('hidden');
outputBox.innerHTML = <p class="quote-text">«${quotes[randomIndex]}»</p>;
triggerAnimation(outputBox);
});
